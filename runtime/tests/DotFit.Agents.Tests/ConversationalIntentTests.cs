namespace DotFit.Agents.Tests;

/// <summary>
/// The conversational branch (plan §11, guardrail intent).
///
/// The defect it closes is worth stating exactly, because the fix looks like a
/// relaxation and is not one: typing "Hi there" ran the whole retrieval chain,
/// hybrid search returned its <c>top</c> neighbours as it does for any query,
/// the answer agent wrote a greeting with no <c>[n]</c>, and the post-check
/// failed it on <c>citation_presence</c> — so under <c>Gated</c> the customer
/// got the support handoff for saying hello. The branch retrieves nothing, so
/// the citation checks (already conditioned on a non-empty source list) have
/// nothing to fire on. No check was loosened, and these tests pin both halves:
/// the greeting is delivered, and every safety precedence still holds.
/// </summary>
public class ConversationalIntentTests
{
    private const string AliasJson = """
        {
          "version": "test-1.0.0",
          "families": [{"family": "Test Family", "canonical_part_no": 9001, "part_nos": [9001], "n_variants": 1}],
          "deterministic_aliases": [],
          "llm_only_aliases": [],
          "context_only_tokens": {},
          "legacy_renames": [],
          "replacements": [],
          "discontinued": []
        }
        """;

    private static GuardrailVerdict Verdict(
        string intent = ConversationIntents.SmallTalk,
        bool escalate = false,
        bool claimTrap = false,
        bool degraded = false) => new()
        {
            Escalate = escalate,
            Reasons = escalate ? ["managed_condition"] : [],
            ClaimTrap = claimTrap,
            Intent = intent,
            Degraded = degraded,
        };

    private static (KnowledgeAssistant Assistant, FakeKnowledgeSearch Search,
                    FakeAnswerAgent Answer, FakeChatReplyAgent Chat, FakeGuardrail Guardrail)
        Build(GuardrailVerdict verdict, IClaimsLanguageChecker? claims = null)
    {
        var guardrail = new FakeGuardrail { Verdict = verdict };
        var search = new FakeKnowledgeSearch { Results = [TestDocs.Product()] };
        var answer = new FakeAnswerAgent { Reply = "A grounded answer [1] about the product." };
        var chat = new FakeChatReplyAgent();
        var assistant = new KnowledgeAssistant(
            guardrail, new FakeRewriter(), AliasTable.FromJson(AliasJson), search, answer,
            new SearchSettings(), claims, chatReply: chat);
        return (assistant, search, answer, chat, guardrail);
    }

    // --- the reported bug ----------------------------------------------------

    [Fact]
    public async Task AGreetingIsAnsweredAndNotWithheld()
    {
        // "Hi there" — the turn that used to come back as the support handoff.
        var (assistant, search, answer, chat, _) = Build(Verdict());

        AssistantResult result = await assistant.AskAsync(
            "Hi there", new AskOptions { StreamMode = AnswerStreamMode.Gated });

        Assert.True(result.PostCheck.Passed);
        Assert.False(result.Withheld);
        Assert.Equal(chat.Reply, result.DeliveredText);
        Assert.DoesNotContain("support team", result.DeliveredText);
        // Nothing was retrieved and nothing was generated by the answer agent.
        Assert.Empty(result.Sources);
        Assert.Empty(search.Calls);
        Assert.Empty(answer.UserMessages);
    }

    [Fact]
    public async Task TheGreetingNeverRunsTheRewriteOrTheAliasExpansion()
    {
        // The branch is placed before them on purpose: there is no query to
        // canonicalize and no product to resolve, and both are model calls or
        // table work spent on a turn that will not search.
        var rewriter = new FakeRewriter();
        var search = new FakeKnowledgeSearch();
        var assistant = new KnowledgeAssistant(
            new FakeGuardrail { Verdict = Verdict() }, rewriter, AliasTable.FromJson(AliasJson),
            search, new FakeAnswerAgent(), new SearchSettings(), null,
            chatReply: new FakeChatReplyAgent());

        AssistantResult result = await assistant.AskAsync("thanks!");

        Assert.Empty(rewriter.Questions);
        Assert.Empty(search.Calls);
        Assert.Equal("thanks!", result.Rewrite.CanonicalQuestion);
        Assert.Empty(result.Expansion.Families);
    }

    [Fact]
    public async Task TheClaimsAuditIsNotRunOnAConversationalTurn()
    {
        // There is nothing to audit an empty source set against — and the
        // verdict log says `not_run` rather than a pass nobody made.
        var claims = new RecordingClaimsChecker();
        var (assistant, _, _, _, _) = Build(Verdict(), claims: claims);

        AssistantResult result = await assistant.AskAsync("hey");

        Assert.Equal(0, claims.Calls);
        Assert.Null(result.PostCheck.Claims);
    }

    // --- precedence: safety first -------------------------------------------

    [Fact]
    public async Task AnEscalationBeatsASmallTalkIntent()
    {
        // "Hi! I'm 14, what should I take?" is a greeting and a hard trigger.
        // The refusal wins, and the branch never sees the turn.
        var (assistant, _, _, chat, _) = Build(
            Verdict(intent: ConversationIntents.SmallTalk, escalate: true));

        AssistantResult result = await assistant.AskAsync("hi! I'm 14, what should I take?");

        Assert.True(result.Escalated);
        Assert.Empty(chat.UserMessages);
        Assert.Contains("healthcare professional", result.DeliveredText);
    }

    [Fact]
    public async Task AClaimTrapBeatsASmallTalkIntent()
    {
        // A presumed disease claim has to be corrected from approved copy,
        // which is only available on the retrieval path.
        var (assistant, search, answer, chat, _) = Build(
            Verdict(intent: ConversationIntents.SmallTalk, claimTrap: true));

        await assistant.AskAsync("hi — so ThermAccel cures diabetes, right?");

        Assert.Single(search.Calls);
        Assert.Single(answer.UserMessages);
        Assert.Empty(chat.UserMessages);
    }

    [Fact]
    public async Task ADegradedGuardrailNeverTakesTheBranch()
    {
        // The pre-check fails open, and failing open means falling back to the
        // fully checked path — never to the one with no sources in it.
        var (assistant, search, _, chat, _) = Build(
            Verdict(intent: ConversationIntents.SmallTalk, degraded: true));

        await assistant.AskAsync("hi there");

        Assert.Single(search.Calls);
        Assert.Empty(chat.UserMessages);
    }

    [Fact]
    public async Task AnOutOfScopeQuestionKeepsTheRetrievalPath()
    {
        // Classified, logged, and otherwise untouched: the §12 adversarial
        // out-of-scope items are delivered today (n_withheld 0), so there is
        // nothing here to reroute.
        var (assistant, search, answer, chat, _) = Build(
            Verdict(intent: ConversationIntents.OutOfScope));

        await assistant.AskAsync("where is my order?");

        Assert.Single(search.Calls);
        Assert.Single(answer.UserMessages);
        Assert.Empty(chat.UserMessages);
    }

    [Theory]
    [InlineData(ConversationIntents.Question)]
    [InlineData(ConversationIntents.OutOfScope)]
    [InlineData("banter")]
    [InlineData("")]
    public void OnlySmallTalkIsConversational(string intent)
    {
        Assert.False(new GuardrailVerdict { Intent = intent }.Conversational);
    }

    [Fact]
    public void AnUnrecognisedIntentReadsAsQuestion()
    {
        // The full retrieval path is the safe default, so an intent nobody
        // recognises is not a licence to skip it.
        Assert.Equal(ConversationIntents.Question, ConversationIntents.Normalize("banter"));
        Assert.Equal(ConversationIntents.Question, ConversationIntents.Normalize(null));
        Assert.Equal(ConversationIntents.SmallTalk, ConversationIntents.Normalize("smalltalk"));
    }

    [Fact]
    public async Task TheGuardrailNormalizesTheIntentItWasGiven()
    {
        var agent = new ChatClientAgent(
            new ScriptedChatClient(
                """{"escalate":false,"reasons":[],"claim_trap":false,"history_trigger":false,"intent":"chit chat","notes":"hello"}"""),
            new ChatClientAgentOptions { Name = "t", ChatOptions = new ChatOptions { Instructions = "t" } });

        GuardrailVerdict verdict = await new AgentGuardrail(agent).CheckAsync("hi", []);

        Assert.Equal(ConversationIntents.Question, verdict.Intent);
        Assert.False(verdict.Conversational);
    }

    [Fact]
    public async Task AVerdictWithNoIntentFieldReadsAsQuestion()
    {
        // Every guardrail reply written before this field existed, and any
        // caller that builds a verdict by hand.
        var agent = new ChatClientAgent(
            new ScriptedChatClient("""{"escalate":false,"reasons":[],"claim_trap":false,"notes":"none"}"""),
            new ChatClientAgentOptions { Name = "t", ChatOptions = new ChatOptions { Instructions = "t" } });

        GuardrailVerdict verdict = await new AgentGuardrail(agent).CheckAsync("how much creatine?", []);

        Assert.Equal(ConversationIntents.Question, verdict.Intent);
    }

    // --- what the branch is allowed to see and say ---------------------------

    [Fact]
    public async Task TheChatReplyIsNotShownTheConversationHistory()
    {
        // The same rule the answer agent has, for a related reason: this branch
        // retrieves nothing, so a fact carried out of an earlier assistant turn
        // would be the one unsourced, unaudited claim in the system.
        var (assistant, _, _, chat, _) = Build(Verdict());
        var history = new List<ConversationTurn>
        {
            new(ConversationRole.User, "how much Test Family should I take?"),
            new(ConversationRole.Assistant, "Two scoops a day, per the approved copy."),
        };

        await assistant.AskAsync("thanks, bye!", new AskOptions { History = history });

        string message = Assert.Single(chat.UserMessages);
        Assert.Contains("thanks, bye!", message);
        Assert.DoesNotContain("Two scoops", message);
        Assert.DoesNotContain("Test Family", message);
    }

    [Fact]
    public async Task AFailedChatCallFallsBackToTheTemplate()
    {
        // Same discipline as every other small-model call here: unavailable
        // degrades to the template, never to an error and never to silence.
        var (assistant, _, _, chat, _) = Build(Verdict());
        chat.Reply = null;

        AssistantResult result = await assistant.AskAsync("hello");

        Assert.Equal(Prompts.SmallTalkMessage(), result.DeliveredText);
        Assert.True(result.PostCheck.Passed);
        Assert.False(result.Withheld);
    }

    [Fact]
    public async Task WithNoChatAgentWiredTheBranchStillAnswers()
    {
        // The dependency is optional, so an older wiring degrades to the
        // template rather than to the defect this branch exists to fix.
        var search = new FakeKnowledgeSearch();
        var assistant = new KnowledgeAssistant(
            new FakeGuardrail { Verdict = Verdict() }, new FakeRewriter(),
            AliasTable.FromJson(AliasJson), search, new FakeAnswerAgent(), new SearchSettings());

        AssistantResult result = await assistant.AskAsync("hi");

        Assert.Equal(Prompts.SmallTalkMessage(), result.DeliveredText);
        Assert.Empty(search.Calls);
    }

    [Fact]
    public void TheTemplatedReplyMakesNoProductClaimAndCitesNothing()
    {
        string reply = Prompts.SmallTalkMessage();

        Assert.Empty(CitationFormatter.ExtractMarkers(reply));
        // It must not read as a refusal either — that is the bug inverted.
        Assert.DoesNotContain("support team", reply);
        Assert.DoesNotContain("healthcare professional", reply);
    }

    [Fact]
    public void TheChatInstructionsForbidProductContentAndCitations()
