    // --- the post-check's reading of a conversational turn -------------------

    [Fact]
    public void AConversationalReplyThatNamesSupportIsNotScoredAsARefusal()
    {
        // "...or contact the dotFIT support team" in a greeting would otherwise
        // trip the model-escalation heuristic and warn on every such turn.
        PostCheckResult result = PostChecker.Check(
            Verdict(), new RewriteResult { CanonicalQuestion = "hi" }, AliasExpansion.Empty, [],
            "Hi! I can point you at the dotFIT support team for orders.");

        Assert.True(result.Passed);
        Assert.Empty(result.Warnings);
    }

    [Fact]
    public void AConversationalReplyThatInventsACitationStillWarns()
    {
        // Nothing was retrieved, so any [n] at all is a marker for a source
        // that does not exist.
        PostCheckResult result = PostChecker.Check(
            Verdict(), new RewriteResult { CanonicalQuestion = "hi" }, AliasExpansion.Empty, [],
            "Hi there [1]!");

        Assert.True(result.Passed);
        Assert.Contains(result.Warnings, w => w.StartsWith("unknown_citations"));
    }

    [Fact]
    public void AConversationalVerdictWithSourcesIsStillScoredAsAnAnswer()
    {
        // The short-circuit is conditioned on the empty source set too: a
        // verdict that says "smalltalk" cannot excuse an answer that was in
        // fact written from retrieved sources.
        IReadOnlyList<RetrievedDocument> sources = [TestDocs.Product()];

        PostCheckResult result = PostChecker.Check(
            Verdict(), new RewriteResult { CanonicalQuestion = "hi" }, AliasExpansion.Empty, sources,
            "Our product does a number of things.");

        Assert.False(result.Passed);
        Assert.Contains(result.Failures, f => f.StartsWith("citation_presence"));
    }

    [Fact]
    public void AClaimsViolationIsStillAFailureOnTheBranch()
    {
        // The short-circuit skips the citation and escalation checks, not the
        // audit — a caller that runs one gets its verdict honoured.
        var claims = new ClaimsVerdict { Compliant = false, Violations = ["cures diabetes"] };

        PostCheckResult result = PostChecker.Check(
            Verdict(), new RewriteResult { CanonicalQuestion = "hi" }, AliasExpansion.Empty, [],
            "Hi! It cures diabetes.", claims);

        Assert.False(result.Passed);
        Assert.Contains(result.Failures, f => f.StartsWith("claims_language"));
    }

    // --- stream shape --------------------------------------------------------

    [Fact]
    public async Task TheGatedBranchEmitsStagesThenOneDeltaAndNoRetraction()
    {
        var (assistant, _, _, chat, _) = Build(Verdict());

        var events = new List<AssistantEvent>();
        await foreach (AssistantEvent e in assistant.AskStreamAsync(
            "hi", new AskOptions { StreamMode = AnswerStreamMode.Gated }))
        {
            events.Add(e);
        }

        Assert.DoesNotContain(events, e => e is RetractionEvent);
        Assert.Equal(["guardrail", "answer", "post-check"],
            events.OfType<StageEvent>().Select(s => s.Stage));
        DeltaEvent delta = Assert.Single(events.OfType<DeltaEvent>());
        Assert.Equal(chat.Reply, delta.Text);
        Assert.IsType<ResultEvent>(events[^1]);
    }

    [Fact]
    public async Task TheGuardrailStageSaysWhichIntentItRead()
    {
        var (assistant, _, _, _, _) = Build(Verdict(intent: ConversationIntents.OutOfScope));

        var events = new List<AssistantEvent>();
        await foreach (AssistantEvent e in assistant.AskStreamAsync("where is my order?"))
            events.Add(e);

        StageEvent stage = events.OfType<StageEvent>().First(s => s.Stage == "guardrail");
        Assert.Equal("clear · out_of_scope", stage.Detail);
    }

    private sealed class RecordingClaimsChecker : IClaimsLanguageChecker
    {
        public int Calls { get; private set; }

        public Task<ClaimsVerdict> CheckAsync(
            string question, string answer, IReadOnlyList<RetrievedDocument> sources,
            IReadOnlyList<string> notes, CancellationToken ct = default)
        {
            Calls++;
            return Task.FromResult(new ClaimsVerdict { Compliant = true });
        }
    }
